#!/usr/bin/env bash
# Pick verified-free random host ports above 10000 and write docker/.env.
# The probe itself is recorded to evidence/g1-lane/port-probe.txt (workspace rule: this is a
# shared machine — never assume a port is free).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
EVID="$ROOT/evidence/g1-lane"
mkdir -p "$EVID"
PROBE="$EVID/port-probe.txt"

: > "$PROBE"
{
  echo "# host port probe — $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# rule: random, >10000, verified free, bound to 127.0.0.1 only"
} >> "$PROBE"

port_free() {
  local p="$1"
  # Free iff nothing is listening (lsof) and no docker publish maps it.
  if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then return 1; fi
  if docker ps --format '{{.Ports}}' 2>/dev/null | grep -q ":${p}->"; then return 1; fi
  return 0
}

pick_port() {
  local label="$1" p tries=0
  while :; do
    tries=$((tries + 1))
    if [ "$tries" -gt 200 ]; then echo "no free port found for $label" >&2; exit 1; fi
    p=$(( (RANDOM % 45000) + 10001 ))
    # skip anything already chosen in this run
    if grep -q " ${p}\$" "$PROBE" 2>/dev/null; then continue; fi
    if port_free "$p"; then
      echo "checked ${label}: candidate ${p} -> FREE (attempt ${tries}) ${p}" >> "$PROBE"
      echo "$p"
      return 0
    fi
    echo "checked ${label}: candidate ${p} -> in use, retrying" >> "$PROBE"
  done
}

PORT_NODE_RPC=$(pick_port node_rpc)
PORT_INDEXER=$(pick_port indexer)
PORT_PROOF_SERVER=$(pick_port proof_server)

# Indexer requires a secret (32 hex bytes); generated per run, never committed.
APP_INFRA_SECRET=$(openssl rand -hex 32)

cat > "$ROOT/docker/.env" <<EOF
# generated by scripts/g1/probe-ports.sh — do not commit
COMPOSE_PROJECT_NAME=aa00003-token-custody
PORT_NODE_RPC=${PORT_NODE_RPC}
PORT_INDEXER=${PORT_INDEXER}
PORT_PROOF_SERVER=${PORT_PROOF_SERVER}
APP_INFRA_SECRET=${APP_INFRA_SECRET}
EOF

{
  echo "selected node_rpc:      ${PORT_NODE_RPC}"
  echo "selected indexer:       ${PORT_INDEXER}"
  echo "selected proof_server:  ${PORT_PROOF_SERVER}"
  echo "compose project name:   aa00003-token-custody"
  echo "APP_INFRA_SECRET:       <generated, 32 bytes hex, not retained in evidence>"
} >> "$PROBE"

echo "ports: node=${PORT_NODE_RPC} indexer=${PORT_INDEXER} proof=${PORT_PROOF_SERVER}"
